test('the homepage is a real, fast-to-understand design library', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /A good idea\. A great identity\./ })).toBeVisible()
  await expect(page.locator('.brand-card')).toHaveCount(12)
  await expect(page.getByRole('status').first()).toContainText('48 identities')
  await expect(page.locator('.repo-hero-panel')).toBeVisible()
  await expect(page.locator('.repo-panel-stats > span')).toHaveCount(3)
  await expect(page.getByRole('link', { name: 'View the repository' })).toHaveAttribute('href', 'https://github.com/arssshi/openform')
  await expect.poll(() => page.locator('.brand-grid img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  expect(errors).toEqual([])
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: testInfo.outputPath('openform-desktop.png'), fullPage: true })
})

