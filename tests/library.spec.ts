test('downloaded kits contain original assets, local fonts, and the install contract', async ({ page, request }) => {
  await page.goto('/brands/moss/')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download kit', exact: true }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe('moss-brand-kit.zip')
  const response = await request.get('/downloads/moss-brand-kit.zip')
  expect(response.ok()).toBe(true)
  const kit = unzipSync(new Uint8Array(await response.body()))
  expect(Object.keys(kit)).toContain('fonts/manrope.ttf')
  expect(Object.keys(kit)).toContain('fonts/instrument-serif-italic-OFL.txt')
  expect(Object.keys(kit)).toContain('theme.json')
  expect(Object.keys(kit)).toContain('AI-PROMPT.md')
  expect(Object.keys(kit)).toContain('install-theme.mjs')
  const theme = JSON.parse(strFromU8(kit['theme.json']))
  expect(theme.scope.selector).toBe('[data-openform="moss"]')
  expect(theme.exports).toHaveLength(30)
  expect(strFromU8(kit['theme.css'])).toContain('[data-openform="moss"]')
  expect(strFromU8(kit['lockup.svg'])).not.toContain('<text')
})

