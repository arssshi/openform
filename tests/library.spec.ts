test('home and identity pages meet automated WCAG AA checks', async ({ page }) => {
  await page.goto('/')
  const home = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(home.violations.map(item => ({ rule: item.id, targets: item.nodes.map(node => node.target) }))).toEqual([])
  await page.goto('/brands/moss/')
  const identity = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(identity.violations.map(item => ({ rule: item.id, targets: item.nodes.map(node => node.target) }))).toEqual([])
})

