test('source and license dialogs link to real archives and documentation', async ({ page, request }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Licenses', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Openform licenses' })).toBeVisible()
  const license = await request.get('/docs/LICENSE-ASSETS.txt')
  expect(await license.text()).toContain('CC0-1.0')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Open source', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Contribute to Openform' })).toBeVisible()
  const source = await request.get('/downloads/openform-source.zip')
  expect(source.ok()).toBe(true)
  const files = unzipSync(new Uint8Array(await source.body()))
  expect(Object.keys(files)).toContain('src/data/systems.json')
  expect(Object.keys(files)).toContain('scripts/build-site.mjs')
  expect(Object.keys(files).some(file => file.startsWith('original-'))).toBe(false)
})
